let currentLang = 'ru';

function initI18n() {
  const saved = localStorage.getItem('mildy_lang');
  if (saved && translations[saved]) {
    currentLang = saved;
  } else {
    // Detect system language
    const navLang = (navigator.language || 'ru').toLowerCase();
    if (navLang.startsWith('kk') || navLang.startsWith('kz')) {
      currentLang = 'kk';
    } else if (navLang.startsWith('en')) {
      currentLang = 'en';
    } else {
      currentLang = 'ru';
    }
  }
  applyTranslations();
}

function setLanguage(lang) {
  if (translations[lang]) {
    currentLang = lang;
    localStorage.setItem('mildy_lang', lang);
    applyTranslations();
  }
}

function t(key) {
  const dict = translations[currentLang] || translations.ru;
  return dict[key] || translations.en[key] || key;
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const text = t(key);
    if (el.tagName === 'INPUT' && el.getAttribute('placeholder')) {
      el.placeholder = text;
    } else {
      el.textContent = text;
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.placeholder = t(key);
  });

  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    el.title = t(key);
  });
}
